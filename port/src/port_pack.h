static inline FILE *Port_NamedPackage(const char *archive, const char *relative,
                                     int64_t *base, int64_t *length, int listIndex,
                                     char *listed, size_t capacity) {
#if defined(__ANDROID__) && !defined(ZENKAIPOWER_ANDROID_INSTALLER)
    return Port_ArchiveLookup(archive,relative,0,base,length,listIndex,listed,capacity);
#else
    char name[1200];
    unsigned char header[12], word[20];
    uint32_t count,i; int64_t total; FILE *fp;
    fp=fopen(archive,"rb"); if (!fp) return NULL;
    if (fread(header,1,12,fp)!=12 || memcmp(header,"BT3TEXT1",8)) goto bad;
    count=Port_PackU32(header+8); if (count>100000) goto bad;
    if (Port_PackSeek(fp,0,SEEK_END) || (total=Port_PackTell(fp))<12 || Port_PackSeek(fp,12,SEEK_SET)) goto bad;
    for (i=0;i<count;i++) {
        uint32_t n; uint64_t offset,size;
        if (fread(word,1,20,fp)!=20) goto bad;
        n=Port_PackU32(word); offset=Port_PackU64(word+4); size=Port_PackU64(word+12);
        if (!n || n>=sizeof(name) || fread(name,1,n,fp)!=n || offset>(uint64_t)total || size>(uint64_t)total-offset || offset>INT64_MAX || size>INT64_MAX) goto bad;
        name[n]=0;
        /* Accept packages generated by older Windows builds too. */
        for (uint32_t j=0;j<n;j++) if (name[j]=='\\') name[j]='/';
        if (listIndex>=0) {
            size_t dirlen=strlen(relative);
            if (!strncmp(name,relative,dirlen) && name[dirlen]=='/' && !strchr(name+dirlen+1,'/')) {
                if (listIndex--==0) {
                    snprintf(listed,capacity,"%s",name+dirlen+1);
                    return fp;
                }
            }
        } else if (!strcmp(name,relative)) {
            *base=(int64_t)offset; *length=(int64_t)size;
            if (Port_PackSeek(fp,*base,SEEK_SET)) goto bad;
            return fp;
        }
    }
bad: fclose(fp); return NULL;
#endif
}
static inline FILE *Port_TextPackage(const char *path, int64_t *base, int64_t *length,
                                    int listIndex, char *listed, size_t capacity) {
    const char *mark=NULL,*relative,*at;
    /* Generated skills have their own package beside game-text.pak. Keep their
       virtual JSON paths so translators and the runtime use the same IDs. */
    at=strstr(path,"/game-text/translations/skills/");
    if(at && listIndex<0) {
        char skills[1200];
        size_t prefix=(size_t)(at-path);
        if(prefix+17<sizeof(skills)) {
            FILE *fp;
            memcpy(skills,path,prefix);strcpy(skills+prefix,"/game-skills.pak");
            fp=Port_NamedPackage(skills,at+strlen("/game-text/translations/skills/"),base,length,-1,NULL,0);
            if(fp) return fp;
        }
    }
    size_t segment=0;
    for (at=path;(at=strstr(at,"/game-info/"))!=NULL;at++) { mark=at; segment=10; }
    for (at=path;(at=strstr(at,"/game-text/"))!=NULL;at++) { mark=at; segment=10; }
    for (at=path;(at=strstr(at,"/disc/"))!=NULL;at++) if (!mark || at>mark) { mark=at; segment=5; }
    for (at=path;(at=strstr(at,"/fonts/"))!=NULL;at++) if (!mark || at>mark) { mark=at; segment=6; }
    for (at=path;(at=strstr(at,"/dragon-net-battle/"))!=NULL;at++) if (!mark || at>mark) { mark=at; segment=18; }
    if (!mark) {
        at=strstr(path,"/translations/");
        if (at) { mark=at; segment=13; }
        else if (!strncmp(path,"translations/",13)) { mark=path; segment=12; }
    }
    if (!mark && !strncmp(path,"fonts/",6)) { mark=path; segment=5; }
    char archive[1200];
    size_t prefix;
    if (!mark) return NULL;
    prefix=(size_t)(mark-path)+segment; relative=path+prefix+1;
    if (prefix+5>=sizeof(archive)) return NULL;
    memcpy(archive,path,prefix); memcpy(archive+prefix,".pak",5);
    return Port_NamedPackage(archive,relative,base,length,listIndex,listed,capacity);
}
/* Regional resources retain their original virtual paths inside one optional pack. */
static inline FILE *Port_MeteorPackage(const char *path, int64_t *base, int64_t *length) {
    const char *mark = strstr(path,"/soundtrack/meteor/");
    char archive[1200];
    size_t prefix;
    if (!mark) mark = strstr(path,"/title/sparking-meteor.bin");
    if (!mark) mark = strstr(path,"/disc/DATA/ZS3JP");
    if (!mark) return NULL;
    prefix=(size_t)(mark-path);
    if (prefix+sizeof("/sparking-meteor.pak")>sizeof(archive)) return NULL;
    memcpy(archive,path,prefix);
    memcpy(archive+prefix,"/sparking-meteor.pak",sizeof("/sparking-meteor.pak"));
    return Port_NamedPackage(archive,mark+1,base,length,-1,NULL,0);
}
static inline int Port_TextPackageList(const char *directory,int index,char *name,size_t capacity) {
    int64_t base,size;
    FILE *fp=Port_TextPackage(directory,&base,&size,index,name,capacity);
    if (!fp) return 0;
    fclose(fp); return 1;
}
static inline FILE *Port_PackOpen(const char *path, int64_t *base, int64_t *length) {
    char archive[1024]; const char *slash=strrchr(path,'/'), *p;
    unsigned char h[8],entry[8]; unsigned long id=0;
    uint32_t count,offset,bytes; int64_t total; FILE *fp; size_t prefix;
    fp=Port_MeteorPackage(path,base,length); if (fp) return fp;
    if (strstr(path,"/game-info/") || strstr(path,"/translations/") || !strncmp(path,"translations/",13) || strstr(path,"/game-text/") || strstr(path,"/disc/") || strstr(path,"/fonts/") || !strncmp(path,"fonts/",6) || strstr(path,"/dragon-net-battle/")) return Port_TextPackage(path,base,length,-1,NULL,0);
    if (!slash || strlen(slash+1)!=9 || strcmp(slash+6,".bin")) return NULL;
    for (p=slash+1;p<slash+6;p++) { if (*p<'0'||*p>'9') return NULL; id=id*10+(*p-'0'); }
    prefix=(size_t)(slash-path); if (prefix+5>=sizeof(archive)) return NULL;
    memcpy(archive,path,prefix); memcpy(archive+prefix,".afs",5);
#if defined(__ANDROID__) && !defined(ZENKAIPOWER_ANDROID_INSTALLER)
    return Port_ArchiveLookup(archive,NULL,id,base,length,-1,NULL,0);
#else
    fp=fopen(archive,"rb"); if (!fp) return NULL;
    if (fread(h,1,8,fp)!=8 || memcmp(h,"AFS\0",4)) goto bad;
    count=Port_PackU32(h+4); if (id>=count || count>1000000) goto bad;
    if (Port_PackSeek(fp,0,SEEK_END) || (total=Port_PackTell(fp))<0 || (uint64_t)count*8+8>(uint64_t)total) goto bad;
    if (Port_PackSeek(fp,8+(int64_t)id*8,SEEK_SET) || fread(entry,1,8,fp)!=8) goto bad;
    offset=Port_PackU32(entry); bytes=Port_PackU32(entry+4);
    if (offset<8+(uint64_t)count*8 || (uint64_t)offset+bytes>(uint64_t)total) goto bad;
    *base=(int64_t)offset; *length=(int64_t)bytes;
    if (Port_PackSeek(fp,*base,SEEK_SET)) goto bad;
    return fp;
bad: fclose(fp); return NULL;
#endif
}
static inline int Port_PackCopy(FILE *src, FILE *dst, int64_t size) {
    unsigned char buf[65536];
    while (size>0) {
        size_t n=(size_t)(size>(int64_t)sizeof(buf)?(int64_t)sizeof(buf):size);
        if (fread(buf,1,n,src)!=n || fwrite(buf,1,n,dst)!=n) return 0;
        size-=(int64_t)n;
    }
    return 1;
}
/* The Windows CRT tmpfile() may write to the drive root, which standard users
 * cannot write. Use a user temp directory and delete the file on close instead. */
static inline FILE *Port_PackTempFile(void) {
#ifdef _WIN32
    const wchar_t *directory=_wgetenv(L"TMP");
    struct _stat64 info;
    if (!directory || _wstat64(directory,&info) || !(info.st_mode&_S_IFDIR))
        directory=_wgetenv(L"TEMP");
    if (!directory || _wstat64(directory,&info) || !(info.st_mode&_S_IFDIR)) return NULL;
    wchar_t *name=_wtempnam(directory,L"zenkaipower");
    if (!name) return NULL;
    int fd=_wopen(name,_O_CREAT|_O_EXCL|_O_RDWR|_O_BINARY|_O_TEMPORARY,_S_IREAD|_S_IWRITE);
    free(name);
    if (fd<0) return NULL;
    FILE *fp=_fdopen(fd,"w+b");
    if (!fp) _close(fd);
    return fp;
#elif defined(__ANDROID__)
    /* bionic's default temp location is not writable by an app. Use the
       private cache supplied by the activity, and unlink immediately. */
    const char *directory=getenv("ZENKAIPOWER_TMPDIR");
    char name[1200];
    if (!directory || snprintf(name,sizeof(name),"%s/zenkaipower-pack-XXXXXX",directory)>=(int)sizeof(name)) return NULL;
    int fd=mkstemp(name);
    if (fd<0) return NULL;
    unlink(name);
    FILE *fp=fdopen(fd,"w+b");
    if (!fp) close(fd);
    return fp;
#else
    return tmpfile();
#endif
}
static inline FILE *Port_PackFopen(const char *path, const char *mode) {
    FILE *fp=fopen(path,mode), *entry,*temp; int64_t base,size;
    if (fp || strcmp(mode,"rb")) return fp;
    entry=Port_PackOpen(path,&base,&size); if (!entry) return NULL;
    temp=Port_PackTempFile();
    if (temp && (!Port_PackCopy(entry,temp,size) || Port_PackSeek(temp,0,SEEK_SET))) { fclose(temp); temp=NULL; }
    fclose(entry); return temp;
}
static inline int Port_PackStat(const char *path, struct stat *st) {
    FILE *fp; int64_t base,size; int result;
    if (stat(path,st)==0) return 0;
    fp=Port_PackOpen(path,&base,&size); if (!fp) return -1;
#ifdef _WIN32
    /* Query the archive with a 64-bit stat too, even for a small entry. */
    struct _stat64 archiveStat;
    result=_fstat64(_fileno(fp),&archiveStat);
    if (result==0) {
        memset(st,0,sizeof(*st));
        st->st_dev=archiveStat.st_dev; st->st_ino=archiveStat.st_ino;
        st->st_mode=archiveStat.st_mode; st->st_nlink=archiveStat.st_nlink;
        st->st_uid=archiveStat.st_uid; st->st_gid=archiveStat.st_gid;
        st->st_rdev=archiveStat.st_rdev;
        st->st_atime=archiveStat.st_atime; st->st_mtime=archiveStat.st_mtime;
        st->st_ctime=archiveStat.st_ctime;
    }
#elif defined(__ANDROID__) && !defined(ZENKAIPOWER_ANDROID_INSTALLER)
    result=Port_ArchiveFileStat(fp,st);
#else
    result=fstat(fileno(fp),st);
#endif
    if (result==0) {
        st->st_size=size;
        if ((int64_t)st->st_size!=size) result=-1;
    }
    fclose(fp); return result;
}
static inline int Port_PackExists(const char *path) {
    int64_t base,size; FILE *fp=fopen(path,"rb");
    if (!fp) fp=Port_PackOpen(path,&base,&size);
    if (!fp) return 0;
    fclose(fp); return 1;
}
