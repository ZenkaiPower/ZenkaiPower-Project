/* Archive positions must stay 64-bit on Windows, where long is 32-bit.
 * POSIX uses off_t; reject an unrepresentable offset on older 32-bit builds. */
static inline int Port_PackSeek(FILE *fp, int64_t offset, int origin) {
#ifdef _WIN32
    return _fseeki64(fp, offset, origin);
#else
    off_t position = (off_t)offset;
    if ((int64_t)position != offset) return -1;
    return fseeko(fp, position, origin);
#endif
}
static inline int64_t Port_PackTell(FILE *fp) {
#ifdef _WIN32
    return _ftelli64(fp);
#else
    return (int64_t)ftello(fp);
#endif
}
static inline uint32_t Port_PackU32(const unsigned char *p) {
    return (uint32_t)p[0] | (uint32_t)p[1]<<8 | (uint32_t)p[2]<<16 | (uint32_t)p[3]<<24;
}
/* Generated text resources use a named, uncompressed package. Entries carry
 * UTF-8 relative names and 64-bit offsets/sizes; no filesystem paths are restored. */
static inline uint64_t Port_PackU64(const unsigned char *p) {
    return (uint64_t)Port_PackU32(p) | (uint64_t)Port_PackU32(p+4)<<32;
}
