static int PortTour_Owned(const SaveData *save, int chara) {
    return save && chara >= 0 && chara < SAVE_CHARA_COUNT &&
        (SAVE_CHARA_WORD(save, chara) & ((u64)1 << (chara % 64))) != 0;
}
static int PortTour_OriginalRoster(const SaveData *save) {
    static const u8 excluded[] = {7,8,9,10,24,38,54,69,70,71,72,75,76,97,110,
        120,145,149,150,151,152,153,154,155,156,157,158,159,160};
    int i, j;
    if (!save) return 0;
    for (i = 0; i < SAVE_CHARA_COUNT; i++) {
        for (j = 0; j < (int)sizeof(excluded); j++) if (excluded[j] == i) break;
        if (j == (int)sizeof(excluded) && !PortTour_Owned(save, i)) return 0;
    }
    return 1;
}
static int PortTour_Available(const SaveData *save, int tour) {
    if (!Port_ZenkaiEnabled()) return 1;
    if (tour < 0 || tour >= 5 || !save) return 0;
    return tour == 0 || tour == 4 || PortTour_OriginalRoster(save) ||
        (save->slot[2].val[1] & 0x7F) == 0x7F;
}
static void PortTour_Eligible(const SaveData *save, u8 *allowed) {
    int i, available = 0, original = PortTour_OriginalRoster(save);
    if (save && !original) for (i = 0; i < 8; i++)
        if (i != 4 && (save->slot[i].flags & 1)) available |= 1 << i;
    for (i = 0; i < SAVE_CHARA_COUNT; i++)
        allowed[i] = PortTour_Owned(save, i) || (sPortTourCharacters[i].sagas & available);
}
static int PortTour_IsIndividual(int chara) {
    return chara == 79 || chara == 109 || chara == 98 || chara == 99;
}
